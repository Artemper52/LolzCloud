'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
function prepare() {
  const plugin = ['playback-control.js', 'repeat-control.js', 'beat-tracker.js', 'tempo-worklet.js', 'sound-effects.js'].map(file => fs.readFileSync(path.join(root, 'source/plugins', file), 'utf8')).join('\n');
  const promotions = fs.readFileSync(path.join(root, 'source/plugins/promotions.js'), 'utf8');
  const code = "// Generated by tools/prepare.cjs from the SoundCloud audio and promotion plugins.\n'use strict';\nconst { contextBridge } = require('electron');\nif (location.protocol === 'https:' && ['soundcloud.com', 'www.soundcloud.com'].includes(location.hostname)) {\n  contextBridge.executeInMainWorld({ func: () => {\n" + plugin + '\n' + promotions + '\n  }});\n}\n';
  fs.writeFileSync(path.join(root, 'source/guest-preload.cjs'), code);
}
if (require.main === module) { prepare(); console.log('Prepared isolated SoundCloud audio hooks.'); }
module.exports = { prepare };
